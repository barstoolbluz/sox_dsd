#!/usr/bin/env python3
"""Content identities of runtime binaries and loader dependencies.

Linux/ldd reports ELF dependencies, not LD_PRELOAD shims or dlopen plugins.
Callers record the latter explicitly.  Libtool's generated executable shell
wrapper must also be resolved to its actual .libs/ ELF and wrapper-supplied
loader search path, or receipts misleadingly fingerprint only the wrapper.
"""
from __future__ import annotations
import hashlib
import os
from pathlib import Path
import re
import shutil
import subprocess
import sys


def digest(path: Path) -> str:
    h = hashlib.sha256()
    with path.open('rb') as stream:
        for block in iter(lambda: stream.read(1 << 20), b''):
            h.update(block)
    return h.hexdigest()


def libtool_runtime(program: Path) -> tuple[Path, dict[str, str]]:
    """Identify a generated libtool wrapper's ELF and actual loader paths.

    Inspect data only; never source or evaluate the wrapper. Ordinary shell
    scripts and direct ELF files are not resolved as libtool wrappers.
    """
    with program.open('rb') as stream:
        header = stream.read(32768)
    if (not header.startswith(b'#!') or
            b'temporary wrapper script for .libs/' not in header or
            b'Generated by libtool' not in header):
        return program, os.environ.copy()
    target = program.parent / '.libs' / program.name
    with target.open('rb') as stream:
        if stream.read(4) != b'\x7fELF':
            raise RuntimeError(f'libtool wrapper target is not an ELF: {target}')
    env = os.environ.copy()
    paths = []
    # A libtool wrapper injects search paths through literal assignments such
    # as LD_LIBRARY_PATH="/build/src/.libs:$LD_LIBRARY_PATH".  Extract only
    # absolute directory literals, never execute shell expressions.
    for value in re.findall(rb'(?m)^\s*LD_LIBRARY_PATH="([^"\n]*)"', header):
        if not value.endswith(b':$LD_LIBRARY_PATH'):
            continue
        for entry in value[:-len(b':$LD_LIBRARY_PATH')].split(b':'):
            path = os.fsdecode(entry)
            if path.startswith('/') and Path(path).is_dir():
                paths.append(path)
    if paths:
        env['LD_LIBRARY_PATH'] = ':'.join(paths + [env.get('LD_LIBRARY_PATH', '')])
    return target.resolve(), env


def executable_libraries(program: Path) -> dict[str, str]:
    if sys.platform != 'linux' or shutil.which('ldd') is None:
        return {}
    target, env = libtool_runtime(program)
    # The wrapper is separately hashed by the caller. A second identity for
    # the actual ELF is essential for shared builds.
    libraries = {str(target): digest(target)} if target != program else {}
    run = subprocess.run(['ldd', str(target)], capture_output=True,
                         text=True, timeout=10, env=env)
    if run.returncode:
        return libraries
    if '=> not found' in run.stdout:
        raise RuntimeError(f'unresolved loader dependency for {target}: {run.stdout}')
    for line in run.stdout.splitlines():
        fields = line.strip().replace('=>', ' ').split()
        path = next((Path(field) for field in fields if field.startswith('/') and
                     Path(field).is_file()), None)
        if path is not None:
            resolved = path.resolve()
            libraries[str(resolved)] = digest(resolved)
    return libraries
