#!/usr/bin/env python3
"""Regression: libtool's executed ELF and shared dependencies are attributed."""
from __future__ import annotations
import hashlib
from pathlib import Path
import tempfile
import unittest
from unittest import mock
import sys
sys.path.insert(0, str(Path(__file__).resolve().parent))
from binary_receipts import executable_libraries, libtool_runtime


class LibtoolReceiptTests(unittest.TestCase):
    def test_wrapped_binary_identified(self):
        with tempfile.TemporaryDirectory() as d:
            root = Path(d)
            (root/'.libs').mkdir()
            (root/'libdir').mkdir()
            wrapper = root/'probe'
            target = root/'.libs/probe'
            target.write_bytes(b'\x7fELF' + b'example-binary')
            wrapper.write_text('#!/bin/sh\n# probe - temporary wrapper script for .libs/probe\n'
                               '# Generated by libtool 2.x\n'
                               f'  LD_LIBRARY_PATH="{root}/libdir:$LD_LIBRARY_PATH"\n')
            elf, env = libtool_runtime(wrapper)
            self.assertEqual(elf, target)
            self.assertTrue(env['LD_LIBRARY_PATH'].startswith(str(root/'libdir')+':'))
            with mock.patch('binary_receipts.subprocess.run') as call:
                call.return_value.returncode = 0
                call.return_value.stdout = ''
                result = executable_libraries(wrapper)
                self.assertEqual(result[str(target)], hashlib.sha256(target.read_bytes()).hexdigest())
                self.assertEqual(call.call_args.kwargs['env']['LD_LIBRARY_PATH'], env['LD_LIBRARY_PATH'])
    def test_ordinary_shell_is_not_guessed(self):
        with tempfile.TemporaryDirectory() as d:
            script = Path(d)/'probe'
            script.write_text('#!/bin/sh\necho unrelated\n')
            got, _ = libtool_runtime(script)
            self.assertEqual(got, script)
    def test_missing_wrapped_executable_fails(self):
        with tempfile.TemporaryDirectory() as d:
            script = Path(d)/'probe'
            script.write_text('#!/bin/sh\n# temporary wrapper script for .libs/probe\n'
                              '# Generated by libtool\n')
            with self.assertRaises(FileNotFoundError):
                libtool_runtime(script)


if __name__ == '__main__':
    unittest.main()
