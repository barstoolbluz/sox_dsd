#!/usr/bin/env python3
"""Generate P10 non-decimating, working-rate Kaiser banks; never analysis-v1.

High-precision generation and a separately implemented extremum search verify
rounded coefficient words. The generator never changes the profile P/S/R.
"""
from __future__ import annotations
import argparse
import hashlib
import json
import math
from pathlib import Path
import mpmath as mp
import numpy as np
from scipy import optimize
from generate_coeffs import design, hexdigest
from certify_filters import bank_extrema, eq_derivative, hp_response
ROOT = Path(__file__).resolve().parents[2]
HEADER = ROOT / 'src/pcmdsd_coeffs.h'
MANIFEST = ROOT / 'tests/dsd/reference/p10_prefilters.json'


def certify(h, p, s):
    stop, count, grid = bank_extrema(h, s, .5)
    xx = np.linspace(0, p, 16385)
    derivative = eq_derivative(h, xx)
    points = [0., p]
    for i in range(len(xx)-1):
        if (derivative[i] < 0) != (derivative[i+1] < 0):
            points.append(float(optimize.brentq(lambda f: eq_derivative(h, f),
                xx[i], xx[i+1], xtol=5e-16)))
    ripple = max(abs(float(20*mp.log10(abs(hp_response(h, f))))) for f in points)
    rejection = -20*math.log10(stop[1])
    return dict(pass_ripple_db=ripple, stop_rejection_db=rejection,
        stop_peak_cycles=stop[0], pass_extrema=len(points), stop_extrema=count,
        dense_stop_rejection_db=-20*math.log10(grid),
        passes=ripple <= .0001 and rejection >= 185.)


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--check', action='store_true')
    args = ap.parse_args()
    mp.mp.dps = 95
    banks = {}
    header = ['/* Generated by tests/dsd/generate_p10_coeffs.py. FIR at R, NOT 2R. */',
              '#ifndef LSX_PCMDSD_COEFFS_H', '#define LSX_PCMDSD_COEFFS_H']
    for name, R, P, S in [('master64_256', 88200, 20000, 40000),
                           ('master128', 176400, 30000, 60000)]:
        p, s = mp.mpf(P)/R, mp.mpf(S)/R
        taps = int(mp.ceil(182/(mp.mpf('2.285')*2*mp.pi*(s-p))))+1
        taps += (1-taps) % 4
        for attempt in range(64):
            values = design(taps, p, s, False)
            proof = certify(np.asarray(values), float(p), float(s))
            if proof['passes']:
                break
            taps += 4
        else:
            raise RuntimeError('coefficient envelope failed: '+name)
        header += [f'static const double lsx_pcmdsd_coeff_{name}[{taps}] = {{',
                   ',\n'.join('  '+v.hex() for v in values), '};']
        banks[name] = dict(length=taps, delay_working_frames=taps//2,
            rounded_hex_sha256=hexdigest(values), pass_cycles_per_input=float(p),
            stop_cycles_per_input=float(s), certificate=proof)
    header += ['#endif', '']
    profiles = [dict(id=f'encode.mastering.v1.dsd{rate//44100}', native_hz=rate,
        working_hz=R, pass_hz=P, stop_hz=S, prefilter_design_hz=R,
        bank=bank, decimation=1) for rate, R, P, S, bank in [
        (2822400,88200,20000,40000,'master64_256'),
        (5644800,176400,30000,60000,'master128'),
        (11289600,176400,40000,80000,'master64_256')]]
    manifest = dict(schema='P10/prefilters/1', arithmetic='95-digit mpmath to binary64',
        generator='tests/dsd/generate_p10_coeffs.py', design_attenuation_db=190,
        beta=19.97926, required_stage_rejection_db=185, pass_envelope_db=.0001,
        method='independent derivative bracketing, 95-digit reevaluation of extrema',
        limitation='numerical extrema evidence, not an interval proof',
        banks=banks, profiles=profiles)
    for path, text in [(HEADER, '\n'.join(header)), (MANIFEST,
            json.dumps(manifest, indent=2, sort_keys=True, allow_nan=False)+'\n')]:
        if args.check:
            if not path.exists() or path.read_text() != text:
                raise RuntimeError('generated bytes differ: '+path.name)
        else:
            path.write_text(text)
    print(json.dumps({k: v['certificate'] | {'taps': v['length']} for k,v in banks.items()}))
    return 0

if __name__ == '__main__':
    raise SystemExit(main())
