#!/usr/bin/env python3
"""P06 reproducible coefficient emission; certification is a separate program.

Use high-precision Kaiser/sinc arithmetic before rounding each symmetric pair
once to IEEE 754 binary64.  No values are loaded from the feasibility NPZ.
Generator must be run from the source tree; --check compares checked-in bytes.
"""
from __future__ import annotations
import argparse
import hashlib
import json
import pathlib
import sys

import mpmath as mp

ROOT = pathlib.Path(__file__).resolve().parents[2]
HEADER = ROOT / 'src/dsd_coeffs.h'
MANIFEST = ROOT / 'tests/dsd/reference/p06_coefficients.json'
mp.mp.dps = 95
A = mp.mpf(190)
BETA = mp.mpf('0.1102') * (A - mp.mpf('8.7'))

# Exact rational P/S values are documented in each bank's stage-input clock.
BANKS = [
    ('halfband', 57, mp.mpf('0.1'), mp.mpf('0.4'), True),
    ('master64_256', 117, mp.mpf(20000) / 176400,
     mp.mpf(40000) / 176400, False),
    ('master128', 153, mp.mpf(30000) / 352800,
     mp.mpf(60000) / 352800, False),
    ('wideband', 257, mp.mpf('0.2'), mp.mpf('0.25'), False),
]
PROFILES = [
    ('master64', 2822400, 88200, 20000, 40000, 'master64_256'),
    ('master128', 5644800, 176400, 30000, 60000, 'master128'),
    ('master256', 11289600, 176400, 40000, 80000, 'master64_256'),
    ('wide64', 2822400, 88200, 35280, 44100, 'wideband'),
    ('wide128', 5644800, 176400, 70560, 88200, 'wideband'),
    ('wide256', 11289600, 352800, 141120, 176400, 'wideband'),
]


def design(length: int, p: mp.mpf, s: mp.mpf, halfband: bool) -> list[float]:
    assert length % 4 == 1
    mid = (length - 1) // 2
    fc = (p + s) / 2
    denominator = mp.besseli(0, BETA)
    half: list[mp.mpf] = []
    for distance in range(mid + 1):
        if not distance:
            val = 2 * fc
        else:
            val = mp.sin(2 * mp.pi * fc * distance) / (mp.pi * distance)
        window = mp.besseli(0, BETA * mp.sqrt(1 - (mp.mpf(2*distance)/(length-1))**2)) / denominator
        val *= window
        if halfband and distance and distance % 2 == 0:
            val = mp.mpf(0)
        half.append(val)
    if halfband:
        half[0] = mp.mpf('0.5')
        side = 2 * mp.fsum(half[1:])
        for i in range(1, len(half)):
            half[i] *= mp.mpf('0.5') / side
    else:
        full = half[0] + 2 * mp.fsum(half[1:])
        half = [h/full for h in half]
    # Equal pairs are emitted from the very same rounded binary64 word.
    values = [float(half[abs(i-mid)]) for i in range(length)]
    if halfband:
        for i in range(length):
            if i != mid and (i-mid) % 2 == 0:
                values[i] = 0.0
        values[mid] = 0.5
    return values


def hexdigest(values: list[float]) -> str:
    # ASCII IEEE hex bit patterns are endian-independent, including signed zero.
    return hashlib.sha256(('\n'.join(v.hex() for v in values)+'\n').encode('ascii')).hexdigest()


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    generated: dict[str, list[float]] = {}
    header = [
        '/* P06 scalar FIR banks: generated by tests/dsd/generate_coeffs.py.',
        ' * Canonical source is the generator; proof is certify_filters.py.',
        ' * Do not hand-edit: SHA-256 covers every rounded coefficient word. */',
        '#ifndef LSX_DSD_COEFFS_H',
        '#define LSX_DSD_COEFFS_H',
        '',
    ]
    meta = {'schema': 'sox-ng/p06-coefficients/1', 'generator': 'tests/dsd/generate_coeffs.py',
            'generator_version': 1, 'arithmetic': 'mpmath (95 decimal digits) to IEEE 754 binary64',
            'mpmath_version': mp.__version__, 'attenuation_design_db': 190,
            'beta_decimal': str(BETA), 'bank_sha256_algorithm': 'sha256 of ASCII float.hex() words joined by newline, terminating newline',
            'banks': {}, 'profiles': {}}
    for name, length, p, s, halfband in BANKS:
        h = design(length, p, s, halfband)
        generated[name] = h
        sym = 'lsx_dsd_coeff_' + name
        header.append('static const double ' + sym + '[' + str(length) + '] = {')
        for offset in range(0, len(h), 4):
            header.append('  '+', '.join(v.hex() for v in h[offset:offset+4]) + (',' if offset+4 < len(h) else ''))
        header.extend(['};', ''])
        meta['banks'][name] = dict(length=length, halfband=halfband,
            pass_cycles_per_input=float(p), stop_cycles_per_input=float(s),
            midpoint_cycles_per_input=float((p+s)/2),
            group_delay_input_samples=(length-1)//2,
            rounded_hex_sha256=hexdigest(h),
            rounded_dc_sum_hex=float(sum(h)).hex())
    header.append('#endif /* LSX_DSD_COEFFS_H */')
    for name, native, output, p, s, last in PROFILES:
        D = native // output
        banks = ['halfband'] * (D.bit_length()-2) + [last]
        G = sum((len(generated[b])-1)//2 * (1 << j) for j, b in enumerate(banks))
        meta['profiles'][name] = dict(native_hz=native, intermediate_hz=output,
            factor=D, pass_hz=p, stop_hz=s, stage_banks=banks,
            delay_native_frames=G, phase_native_frames=G%D,
            discard_output_frames=G//D, stage_phases=[(G>>j)&1 for j in range(len(banks))])
    outputs = [(HEADER, '\n'.join(header)+'\n'), (MANIFEST, json.dumps(meta,sort_keys=True, indent=2)+'\n')]
    if args.check:
        for path, content in outputs:
            if not path.exists() or path.read_text() != content:
                print('MISMATCH '+str(path), file=sys.stderr)
                return 1
        print('Coefficient generation deterministic: header and manifest match')
        return 0
    for path, content in outputs:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)
    print('Generated P06 banks:', ', '.join(f'{name}={len(h)}' for name,h in generated.items()))
    return 0

if __name__ == '__main__':
    raise SystemExit(main())
